"""Packages ORACLE's data for the dashboard.

Checks that data/oracle.json is valid, then writes:
  dashboard/data.js        everything the dashboard shows (ledger, simulation, agents, recent events,
                           key numbers, latest briefing)
  dashboard/artifact.html  the dashboard page without its <html>/<head>/<body> wrapper; this is the
                           version published online (the host adds its own wrapper)
  docs/index.html, docs/data.js
                           the phone app served by GitHub Pages: the same page plus what makes it an
                           installable home-screen app (manifest, icons, offline support). The static app
                           files in docs/ (manifest.webmanifest, sw.js, icons) are not touched here.
  scorecard.md

Usage:  python tools/build.py
"""
import datetime as dt
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DASH = ROOT / "dashboard"
DOCS = ROOT / "docs"

# Added to the phone-app copy of the page, just before </head>.
PWA_HEAD = """<link rel="manifest" href="manifest.webmanifest">
<meta name="theme-color" content="#0d0d0d">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="ORACLE">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<link rel="icon" type="image/png" href="icon-192.png">
<style>
  /* Installed app: keep content clear of the phone's status bar and home indicator. */
  .wrap { padding-top: calc(20px + env(safe-area-inset-top, 0px)); padding-bottom: calc(64px + env(safe-area-inset-bottom, 0px)); }
</style>
"""
# Added just before </body>.
PWA_BODY = """<script>
  // Phone app: works offline, and reloads for fresh numbers when reopened after 30+ minutes away.
  if ('serviceWorker' in navigator) { navigator.serviceWorker.register('sw.js').catch(function () {}); }
  (function () {
    var loaded = Date.now();
    document.addEventListener('visibilitychange', function () {
      if (document.visibilityState === 'visible' && Date.now() - loaded > 30 * 60 * 1000) { location.reload(); }
    });
  })();
</script>
"""


def load(path, default=None):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def js(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def write_scorecard(db):
    """scorecard.md, generated from the numbers tools/core.py computed."""
    st = db.get("stats") or {}
    f = lambda x: "—" if x is None else f"{x:.3f}"

    def row(name, b):
        return (f"| {name} | {b.get('n', 0)} | {b.get('hits', 0)} / {b.get('misses', 0)} | {f(b.get('brier_oracle'))} | "
                f"{f(b.get('brier_clio'))} | {f(b.get('brier_omen'))} | {f(b.get('brier_sim'))} (n={b.get('n_sim', 0)}) | "
                f"{f(b.get('brier_market'))} (n={b.get('n_market', 0)}) |")

    lines = [f"# ORACLE Scorecard", "", f"_Generated by tools/build.py · last run {db['meta']['last_run']}_", "",
             "**Brier score:** 0 = perfect, 0.25 = coin-flip guessing. Lower is better. "
             "**Right / wrong** counts a forecast above 50% that happened, or below 50% that didn't, as right.", "",
             "| | Resolved | Right / wrong | ORACLE | CLIO | OMEN | Sandbox | Market |", "|---|---|---|---|---|---|---|---|",
             row("**All**", st.get("all", {}))]
    for dom, b in (st.get("by_domain") or {}).items():
        lines.append(row(dom.title(), b))
    lines += ["", "## Engine weights (CLIO / OMEN)",
              " · ".join(f"{k.title()} {v['clio']:.2f}/{v['omen']:.2f}" for k, v in db.get("weights", {}).items()),
              f"_Each result multiplies an engine's weight by exp(−{db.get('config', {}).get('eta', 0.5)} × its Brier score), "
              f"so the closer engine gains a few points. Limits: 20%–80%._", "", "## Calibration",
              "| ORACLE said | Count | Average forecast | Actually happened |", "|---|---|---|---|"]
    for b in st.get("calibration", []):
        lines.append(f"| {b['range']} | {b['n']} | {'—' if b['avg_forecast'] is None else f'{b['avg_forecast']:.0%}'} | "
                     f"{'—' if b['happened'] is None else f'{b['happened']:.0%}'} |")
    lines += ["", "_Well calibrated means the last two columns match. Needs about 8+ results per row to mean much._", "",
              "## Lessons", *[f"- {l['date']}{' (prior)' if l.get('source') == 'prior' else ''}: {l['text']}" for l in db.get("lessons", [])], ""]
    (ROOT / "scorecard.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    try:
        db = load(DATA / "oracle.json")
    except json.JSONDecodeError as ex:
        print(f"ERROR: data/oracle.json is NOT valid JSON: {ex}")
        sys.exit(1)
    for name in ("events.json", "model.json", "sim.json", "metrics.json"):
        try:
            load(DATA / name)
        except json.JSONDecodeError as ex:
            print(f"ERROR: data/{name} is NOT valid JSON: {ex}")
            sys.exit(1)

    sim = load(DATA / "sim.json", None)
    model = load(DATA / "model.json", {"agents": []})
    agents = [{"id": a["id"], "name": a["name"], "description": a.get("description", "")} for a in model["agents"]]
    cutoff = (dt.date.today() - dt.timedelta(days=90)).isoformat()
    events = [e for e in (load(DATA / "events.json", {"events": []})["events"]) if e["date"] >= cutoff]
    metrics = load(DATA / "metrics.json", None)
    if metrics:
        for s in metrics.get("series", {}).values():
            if "history" in s:
                s["history"] = s["history"][-90:]

    briefing = None
    files = sorted(p for p in (ROOT / "briefings").glob("*.md") if re.fullmatch(r"\d{4}-\d{2}-\d{2}", p.stem))
    if files:
        briefing = {"date": files[-1].stem, "markdown": files[-1].read_text(encoding="utf-8")}

    DASH.mkdir(exist_ok=True)
    out = ["// AUTO-GENERATED by tools/build.py. Do not edit by hand.",
           f"window.ORACLE_DATA = {js(db)};",
           f"window.ORACLE_SIM = {js(sim)};",
           f"window.ORACLE_AGENTS = {js(agents)};",
           f"window.ORACLE_EVENTS = {js(events)};",
           f"window.ORACLE_METRICS = {js(metrics)};",
           f"window.ORACLE_BRIEFING = {js(briefing)};", ""]
    data_js = "\n".join(out)
    (DASH / "data.js").write_text(data_js, encoding="utf-8", newline="\n")

    source = (DASH / "index.html").read_text(encoding="utf-8")

    # phone app (GitHub Pages)
    if source.count("</head>") != 1 or source.count("</body>") != 1:
        print("ERROR: dashboard/index.html must contain exactly one </head> and one </body> for the phone-app build.")
        sys.exit(1)
    DOCS.mkdir(exist_ok=True)
    app = source.replace("</head>", PWA_HEAD + "</head>").replace("</body>", PWA_BODY + "</body>")
    (DOCS / "index.html").write_text(app, encoding="utf-8", newline="\n")
    (DOCS / "data.js").write_text(data_js, encoding="utf-8", newline="\n")
    missing = [f for f in ("manifest.webmanifest", "sw.js", "icon-192.png", "icon-512.png", "apple-touch-icon.png")
               if not (DOCS / f).exists()]
    if missing:
        print(f"WARNING: phone-app files missing from docs/: {', '.join(missing)} (icons: run tools/make_icons.py)")

    page = source
    for pat in (r"(?im)^\s*<!doctype html>\s*\n", r"(?im)^\s*</?html[^>]*>\s*\n", r"(?im)^\s*</?head>\s*\n",
                r"(?im)^\s*</?body>\s*\n", r"(?im)^\s*<meta [^>]*>\s*\n"):
        page = re.sub(pat, "", page)
    (DASH / "artifact.html").write_text(page, encoding="utf-8", newline="\n")

    write_scorecard(db)

    preds = db.get("predictions", [])
    n_open = sum(1 for p in preds if p.get("status") == "open")
    n_res = sum(1 for p in preds if p.get("status") == "resolved")
    print(f"OK: data valid. {n_open} open, {n_res} resolved, {len(db.get('systems', []))} systems, "
          f"{len(db.get('catalysts', []))} catalysts, {len(events)} recent events. "
          f"Briefing: {files[-1].name if files else 'none'}. Wrote dashboard/data.js, dashboard/artifact.html, "
          f"docs/index.html and docs/data.js")


if __name__ == "__main__":
    main()
